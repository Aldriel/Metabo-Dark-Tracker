package com.bioinfo.metabodark.desktop.model;

import com.bioinfo.metabodark.desktop.prefs.UserPreferences;
import com.bioinfo.metabodark.example.SimulatedStudy;
import com.bioinfo.metabodark.model.AnalysisSettings;
import com.bioinfo.metabodark.model.Language;
import com.bioinfo.metabodark.parse.ParseException;
import com.bioinfo.metabodark.report.PdfReportWriter;
import com.bioinfo.metabodark.report.ResultTableWriter;
import com.bioinfo.metabodark.service.Analysis;
import com.bioinfo.metabodark.service.MetaboService;

import java.nio.charset.StandardCharsets;

/**
 * State of the desktop application: the open file, the settings and the latest annotation.
 *
 * <p>The view never calls {@link MetaboService}. A method that rejects a value returns the error
 * code and leaves the previous settings in place.
 */
public final class DesktopModel {

    private final MetaboService service;
    private final UserPreferences preferences;
    private byte[] content;
    private String fileName = "";
    private boolean simulated;
    private AnalysisSettings settings = AnalysisSettings.defaults();
    private Analysis analysis;
    private String errorCode;
    private int fontSize;

    /**
     * Model that remembers language and text size in {@code preferences}.
     *
     * @param service annotation pipeline
     * @param preferences user preferences
     */
    public DesktopModel(MetaboService service, UserPreferences preferences) {
        this.service = service;
        this.preferences = preferences;
        this.fontSize = preferences.fontSize();
    }

    /** Opens the simulated plasma. */
    public void openExample() {
        open(SimulatedStudy.bytes(), SimulatedStudy.FILE_NAME, true);
    }

    /**
     * Opens a file.
     *
     * @param bytes mzML or mzXML
     * @param name file name
     * @param simulatedData {@code true} only for the built-in example
     */
    public void open(byte[] bytes, String name, boolean simulatedData) {
        try {
            Analysis next =
                    service.analyze(bytes, name == null ? "" : name, settings, simulatedData);
            content = bytes.clone();
            fileName = name == null ? "" : name;
            simulated = simulatedData;
            analysis = next;
            errorCode = null;
        } catch (ParseException e) {
            content = null;
            fileName = "";
            simulated = false;
            analysis = null;
            errorCode = e.code().name();
        }
    }

    /** Latest annotation, or {@code null} when no file is open. */
    public Analysis analysis() {
        return analysis;
    }

    /** Settings currently in use. */
    public AnalysisSettings settings() {
        return settings;
    }

    /** Name of the open file, or blank. */
    public String fileName() {
        return fileName;
    }

    /** Whether the open file was generated by Metabo-Dark Tracker. */
    public boolean simulated() {
        return simulated;
    }

    /** Code of the last error, or {@code null}. */
    public String errorCode() {
        return errorCode;
    }

    /** Current language. */
    public Language language() {
        return preferences.language();
    }

    /** Remembers a new language. */
    public void language(Language language) {
        preferences.language(language);
    }

    /** Current text size, in pixels. */
    public int fontSize() {
        return fontSize;
    }

    /** Changes the text size by one pixel, inside the allowed range. */
    public void changeFont(int delta) {
        fontSize(fontSize + delta);
    }

    /** Restores the default text size. */
    public void resetFont() {
        fontSize(UserPreferences.DEFAULT_FONT);
    }

    /** Sets an exact text size. */
    public void fontSize(int size) {
        fontSize = UserPreferences.clamp(size);
        preferences.fontSize(fontSize);
    }

    /**
     * Replaces the matching window. Returns an error code, or {@code null}.
     *
     * @param tolerance absolute m/z window
     * @param cosine minimum cosine
     * @param queryPublic whether the public databases may be called
     * @return an error code, or {@code null} when the annotation was recomputed
     */
    public String setNumbers(double tolerance, double cosine, boolean queryPublic) {
        if (content == null) {
            errorCode = "NO_FILE";
            return errorCode;
        }
        AnalysisSettings next;
        try {
            next = new AnalysisSettings(tolerance, cosine, queryPublic);
        } catch (IllegalArgumentException e) {
            errorCode = e.getMessage();
            return errorCode;
        }
        settings = next;
        errorCode = null;
        rerun();
        return null;
    }

    /** Tab-separated table, or blank when nothing is open. */
    public String export() {
        if (analysis == null) {
            return "";
        }
        return new String(ResultTableWriter.write(analysis), StandardCharsets.UTF_8);
    }

    /**
     * PDF report of the current annotation.
     *
     * @param title title typed by the visitor
     * @return the PDF, or an empty array when nothing is open
     */
    public byte[] report(String title) {
        if (analysis == null) {
            return new byte[0];
        }
        return PdfReportWriter.write(analysis, preferences.language(), title);
    }

    private void rerun() {
        analysis = service.analyze(content, fileName, settings, simulated);
    }
}
